uint8_t expand_coordinate_point(uint8_t *array, uint16_t x_len, uint16_t y_len){
    // 创建临时矩阵用于存储扩展后的值
    uint8_t expanded_matrix[COORDINATE_MATRIX_X_RESOLUTION][COORDINATE_MATRIX_Y_RESOLUTION] = {0};

    // 遍历原始矩阵中的每个点
    for(uint16_t x = 0; x < x_len; x++) {
        for(uint16_t y = 0; y < y_len; y++) {
            // 如果当前点是接触点
            if(array[x * y_len + y] == 1) {
                // 设置中心点的影响值
                expanded_matrix[x][y] = IMPACT_FACTOR;

                // 向四周扩展,计算影响值
                for(int16_t dx = -KNN_K; dx <= KNN_K; dx++) {
                    for(int16_t dy = -KNN_K; dy <= KNN_K; dy++) {
                        // 跳过中心点
                        if(dx == 0 && dy == 0) continue;

                        int16_t new_x = x + dx;
                        int16_t new_y = y + dy;

                        // 检查是否在矩阵范围内
                        if(new_x >= 0 && new_x < x_len &&
                           new_y >= 0 && new_y < y_len) {
                            // 计算到中心点的距离
                            int16_t distance = abs(dx) + abs(dy);
                            // 计算影响值
                            int16_t impact = IMPACT_FACTOR - (distance * DECREASING_PARAM);

                            // 如果新的影响值大于当前值，则更新
                            if(impact > expanded_matrix[new_x][new_y]) {
                                expanded_matrix[new_x][new_y] = impact;
                            }
                        }
                    }
                }
            }
        }
    }

    // 将扩展后的值复制回原始数组
    for(uint16_t x = 0; x < x_len; x++) {
        for(uint16_t y = 0; y < y_len; y++) {
            array[x * y_len + y] = expanded_matrix[x][y];
        }
    }

    // 输出扩展后的矩阵
//    printf("\nExpanded coordinate matrix:\n");
//    for(uint16_t x = 0; x < x_len; x++) {
//        for(uint16_t y = 0; y < y_len; y++) {
//            printf("%3d ", array[x * y_len + y]);
//        }
//        printf("\n");
//    }
    return 1;
}

